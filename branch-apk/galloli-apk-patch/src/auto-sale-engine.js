// src/native/auto-sale-engine.js
//
// Orquestador: combina geofence + balanza BLE + decisión de venta.
// Solo se ejecuta en APK nativo (verificado via platform-guard).

import { isApkNative, assertApkOrNoop } from './platform-guard.js';
import { initBleScale, onWeight, onConnected, onDisconnect } from './ble-scale.js';
import { startGeofence, onEnter, onExit, getCurrentZone } from './geofence-manager.js';
import { LocalNotifications } from '@capacitor/local-notifications';
import { Preferences } from '@capacitor/preferences';
import { App } from '@capacitor/app';
import { initFcm } from './fcm-handler.js';
import { registerPlugin } from '@capacitor/core';

// Bridge mínimo al Foreground Service Kotlin (usa un plugin pequeño o
// el `@capacitor/background-runner`; aquí usamos una llamada directa
// vía un plugin propio "BgService" que arranca el servicio).
const BgService = registerPlugin('BgService');

const DEFAULTS = {
  mode: 'auto',                 // 'auto' | 'confirm'
  minWeightKg: 0.5,
  stableReadings: 3,
  stableWindowMs: 2000,
  minIntervalSamePlaceMs: 60_000,
  geofenceRadiusM: 35,
  sriEnabled: false,
};

let cfg = { ...DEFAULTS };
let weightBuffer = [];
let lastSaleByClient = new Map();   // clientId -> timestamp ms
let pendingConfirmId = null;

export async function initNativeAutoSale(userCfg = {}) {
  if (!assertApkOrNoop('auto-sale-engine')) return;
  cfg = { ...DEFAULTS, ...userCfg };

  // Permisos notificación
  await LocalNotifications.requestPermissions();
  await registerNotificationActions();

  // Arranca el Foreground Service (mantiene BLE+GPS vivos)
  try { await BgService.start({ text: 'Esperando clientes' }); } catch {}

  // Carga clientes con coords desde tu IndexedDB (función expuesta por modules.js)
  const clients = await loadClientsWithCoords();

  await startGeofence(clients, cfg.geofenceRadiusM);

  const savedScale = (await Preferences.get({ key: 'galloli.scale.deviceId' })).value;
  await initBleScale(savedScale);

  // FCM solo para comandos remotos (pause/resume/forceSync/changeMode)
  await initFcm({
    onCommand: handleRemoteCommand,
  });

  // Listeners
  onEnter(zone => {
    weightBuffer = [];
    updateBgText(`En zona de ${zone.name} · esperando peso`);
  });
  onExit(zone => {
    weightBuffer = [];
    updateBgText('Esperando clientes');
  });
  onWeight(kg => onWeightReading(kg));
  onConnected(() => console.info('[galloli] balanza conectada'));
  onDisconnect(() => console.warn('[galloli] balanza desconectada'));

  // Si el usuario tap en notificación de confirmación
  LocalNotifications.addListener('localNotificationActionPerformed', async (ev) => {
    if (!pendingConfirmId || ev.notification.id !== pendingConfirmId) return;
    if (ev.actionId === 'CONFIRM') {
      await commitSale(ev.notification.extra);
    }
    pendingConfirmId = null;
  });

  // Limpieza al cerrar la app desde recents (el FG service sobrevive igual)
  App.addListener('appStateChange', s => {
    console.debug('[galloli] appState', s);
  });
}

function onWeightReading(kg) {
  const zone = getCurrentZone();
  if (!zone) return;                          // fuera de geofence: ignora
  if (kg < cfg.minWeightKg) return;           // ruido / balanza vacía

  const now = Date.now();
  weightBuffer = weightBuffer.filter(r => now - r.t < cfg.stableWindowMs);
  weightBuffer.push({ kg, t: now });

  if (weightBuffer.length < cfg.stableReadings) return;

  // Estabilidad: spread < 30g
  const kgs = weightBuffer.map(r => r.kg);
  const spread = Math.max(...kgs) - Math.min(...kgs);
  if (spread > 0.03) return;

  const stableKg = +(kgs.reduce((a,b) => a+b, 0) / kgs.length).toFixed(3);

  // Dedupe: una venta por cliente cada minIntervalSamePlaceMs
  const last = lastSaleByClient.get(zone.id) || 0;
  if (now - last < cfg.minIntervalSamePlaceMs) return;

  weightBuffer = [];
  lastSaleByClient.set(zone.id, now);

  const sale = buildSaleDraft(zone, stableKg);

  if (cfg.mode === 'auto') {
    commitSale(sale);
  } else {
    promptConfirm(sale);
  }
}

function buildSaleDraft(zone, kg) {
  // Adapta a tu lógica real (precio por kg del cliente o producto fijo)
  const pricePerKg = zone.pricePerKg || 3.0;
  const total = +(kg * pricePerKg).toFixed(2);
  return {
    clientId: zone.id,
    clientName: zone.name,
    weightKg: kg,
    pricePerKg,
    total,
    ts: Date.now(),
    autoGenerated: true,
    sriSent: false,             // ⚠️ no facturar SRI (cfg.sriEnabled = false)
  };
}

async function commitSale(sale) {
  // Llama a la función que ya tiene tu modules.js para registrar venta local
  // (o cae a un evento global que tu app escuche).
  if (window.galloli && typeof window.galloli.registerSale === 'function') {
    await window.galloli.registerSale(sale);
  } else {
    // Fallback: guarda directo en IndexedDB
    window.dispatchEvent(new CustomEvent('galloli:auto-sale', { detail: sale }));
  }

  await LocalNotifications.schedule({
    notifications: [{
      id: Math.floor(Math.random()*1e6),
      title: 'Venta registrada',
      body: `${sale.clientName} · ${sale.weightKg} kg · $${sale.total.toFixed(2)}`,
      smallIcon: 'ic_stat_icon_config_sample',
    }],
  });

  updateBgText(`Última: ${sale.clientName} ${sale.weightKg}kg`);
}

async function promptConfirm(sale) {
  pendingConfirmId = Math.floor(Math.random()*1e6);
  await LocalNotifications.schedule({
    notifications: [{
      id: pendingConfirmId,
      title: 'Confirmar venta',
      body: `${sale.clientName} · ${sale.weightKg} kg · $${sale.total.toFixed(2)}`,
      actionTypeId: 'SALE_CONFIRM',
      extra: sale,
      ongoing: true,
      autoCancel: false,
    }],
  });

  // timeout 60s
  setTimeout(async () => {
    if (pendingConfirmId) {
      await LocalNotifications.cancel({ notifications: [{ id: pendingConfirmId }] });
      pendingConfirmId = null;
    }
  }, 60_000);
}

async function registerNotificationActions() {
  await LocalNotifications.registerActionTypes({
    types: [{
      id: 'SALE_CONFIRM',
      actions: [
        { id: 'CONFIRM', title: 'Confirmar' },
        { id: 'CANCEL',  title: 'Cancelar', destructive: true },
      ],
    }],
  });
}

async function updateBgText(text) {
  try { await BgService.updateText({ text }); } catch {}
}

async function loadClientsWithCoords() {
  if (window.galloli && typeof window.galloli.listClientsWithCoords === 'function') {
    return await window.galloli.listClientsWithCoords();
  }
  return [];
}

function handleRemoteCommand(cmd) {
  switch (cmd.type) {
    case 'pause':       cfg.mode = 'confirm'; break;
    case 'resume':      cfg.mode = 'auto'; break;
    case 'reload':      window.location.reload(); break;
    case 'set-radius':  cfg.geofenceRadiusM = cmd.value; break;
  }
}
